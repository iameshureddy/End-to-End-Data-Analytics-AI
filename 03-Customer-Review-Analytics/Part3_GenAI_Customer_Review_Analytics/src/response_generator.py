# =============================================================================
# IMPORTS
# =============================================================================

import os
import json
import pandas as pd

from config import CLEAN_DATA
from retry_handler import safe_call_llm


# =============================================================================
# CONFIGURATION
# =============================================================================

TASK5_OUTPUT = "output/csv/aspect_sentiment_results.csv"
OUTPUT_FILE = "output/customer_responses.csv"

# The rubric requires at least 3 generated responses.
NUMBER_OF_REVIEWS = 3

os.makedirs("output", exist_ok=True)


# =============================================================================
# RESPONSE CLEANING
# =============================================================================

def clean_response(text):
    """
    Clean minor formatting issues from the Gemini-generated response.

    Parameters
    ----------
    text : str
        Generated customer response.

    Returns
    -------
    str
        Cleaned customer response.
    """

    if text is None:
        return ""

    text = str(text).strip()

    # Fix common spacing issues in generated text.
    replacements = {
        "andhow": "and how",
        "useyour": "use your",
        "sizingmeasurements": "sizing measurements",
        "dress.While": "dress. While",
        "material.While": "material. While",
        "fit.While": "fit. While",
        "experience.We": "experience. We",
        "feedback.We": "feedback. We",
    }

    for old, new in replacements.items():
        text = text.replace(old, new)

    return text


# =============================================================================
# LOAD CUSTOMER REVIEWS
# =============================================================================

def load_customer_reviews():
    """
    Load customer reviews from the cleaned dataset.

    Returns
    -------
    dict
        Mapping of Review No to customer review text.
    """

    if not os.path.exists(CLEAN_DATA):
        raise FileNotFoundError(
            f"Cleaned dataset not found:\n{CLEAN_DATA}"
        )

    df = pd.read_csv(CLEAN_DATA)

    if "Review Text" not in df.columns:
        raise ValueError(
            "The cleaned dataset does not contain the 'Review Text' column."
        )

    # Task 5 processes the first 10 cleaned reviews.
    reviews = df["Review Text"].head(10).tolist()

    review_mapping = {
        index: review
        for index, review in enumerate(reviews, start=1)
    }

    return review_mapping


# =============================================================================
# LOAD TASK 5 OUTPUT
# =============================================================================

def load_task5_results():
    """
    Load the structured aspect-based sentiment results generated by Task 5.

    Returns
    -------
    pandas.DataFrame
        Task 5 structured output.
    """

    if not os.path.exists(TASK5_OUTPUT):
        raise FileNotFoundError(
            "\nTask 5 output file was not found:\n"
            f"{TASK5_OUTPUT}\n\n"
            "Please run Task 5 first:\n"
            "python src/aspect_sentiment.py"
        )

    task5_df = pd.read_csv(TASK5_OUTPUT)

    required_columns = [
        "Review No",
        "Aspect",
        "Sentiment",
        "Action",
        "Overall Sentiment",
        "Status"
    ]

    missing_columns = [
        column
        for column in required_columns
        if column not in task5_df.columns
    ]

    if missing_columns:
        raise ValueError(
            "Task 5 output is missing the following required columns: "
            + ", ".join(missing_columns)
        )

    return task5_df


# =============================================================================
# BUILD STRUCTURED TASK 5 ANALYSIS
# =============================================================================

def build_structured_analysis(task5_rows):
    """
    Convert all Task 5 aspect records belonging to one review
    into one structured dictionary.

    Parameters
    ----------
    task5_rows : pandas.DataFrame
        Task 5 records for one review.

    Returns
    -------
    dict
        Structured analysis for the review.
    """

    aspects = []
    overall_sentiment = ""

    for _, row in task5_rows.iterrows():

        aspect = str(row["Aspect"]).strip()
        sentiment = str(row["Sentiment"]).strip()
        action = str(row["Action"]).strip()

        if aspect:
            aspects.append({
                "aspect": aspect,
                "sentiment": sentiment,
                "action": action
            })

        overall = str(row["Overall Sentiment"]).strip()

        if overall and overall.lower() != "nan":
            overall_sentiment = overall

    return {
        "aspects": aspects,
        "overall_sentiment": overall_sentiment
    }


# =============================================================================
# TASK 6 RESPONSE PROMPT
# =============================================================================

def build_task6_response_prompt(review, structured_output):
    """
    Build the second LLM prompt using the structured output
    generated by Task 5.

    Parameters
    ----------
    review : str
        Original customer review.

    structured_output : dict
        Structured Task 5 analysis.

    Returns
    -------
    str
        Customer response-generation prompt.
    """

    structured_json = json.dumps(
        structured_output,
        indent=2,
        ensure_ascii=False
    )

    prompt = f"""
You are a Senior Customer Support Executive.

You need to respond to a customer using the customer's original review
and the structured Aspect-Based Sentiment Analysis generated in Task 5.

CUSTOMER REVIEW:
{review}

STRUCTURED TASK 5 ANALYSIS:
{structured_json}

INSTRUCTIONS:

1. Thank the customer for sharing their feedback.
2. Address the specific issues identified in the structured analysis.
3. Appreciate positive feedback when positive aspects are present.
4. Apologize for negative experiences when negative aspects are present.
5. Mention relevant improvements when appropriate.
6. Make the response specific to this customer's review.
7. Use the structured Task 5 analysis when drafting the response.
8. Do not invent information that is not supported by the review.
9. Keep the response between 2 and 4 sentences.
10. Make the response natural, professional, and empathetic.
11. Do not use a generic template response.
12. Return ONLY the customer reply.
"""

    return prompt.strip()


# =============================================================================
# MAIN PROGRAM
# =============================================================================

if __name__ == "__main__":

    print("=" * 70)
    print("TASK 6 : Prompt Chaining for Customer Response Generation")
    print("=" * 70)

    # -------------------------------------------------------------------------
    # STEP 1 - LOAD CUSTOMER REVIEWS
    # -------------------------------------------------------------------------

    print("\nLoading customer reviews...")

    try:
        review_mapping = load_customer_reviews()

        print(
            f"Loaded {len(review_mapping)} reviews from cleaned dataset."
        )

    except Exception as error:

        print("\nERROR while loading customer reviews:")
        print(error)

        raise SystemExit(1)

    # -------------------------------------------------------------------------
    # STEP 2 - LOAD TASK 5 OUTPUT
    # -------------------------------------------------------------------------

    print("\nLoading Task 5 structured output...")

    try:
        task5_df = load_task5_results()

        print(
            f"Loaded {len(task5_df)} aspect-level records from Task 5."
        )

    except Exception as error:

        print("\nERROR while loading Task 5 output:")
        print(error)

        raise SystemExit(1)

    # -------------------------------------------------------------------------
    # STEP 3 - SELECT REVIEWS
    # -------------------------------------------------------------------------

    available_review_numbers = sorted(
        task5_df["Review No"]
        .dropna()
        .astype(int)
        .unique()
    )

    selected_review_numbers = available_review_numbers[
        :NUMBER_OF_REVIEWS
    ]

    print(
    f"\nReviews selected for Task 6: "
    f"{selected_review_numbers}"
)

    # -------------------------------------------------------------------------
    # STEP 4 - GENERATE CUSTOMER RESPONSES
    # -------------------------------------------------------------------------

    responses = []

    for review_no in selected_review_numbers:

        review_no = int(review_no)

        print("\n" + "=" * 70)
        print(f"Processing Review {review_no}")
        print("=" * 70)

        # ---------------------------------------------------------------------
        # Retrieve original review
        # ---------------------------------------------------------------------

        review = review_mapping.get(review_no)

        if review is None:

            print(
                f"Review {review_no} was not found in the cleaned dataset."
            )

            responses.append({
                "Review No": review_no,
                "Customer Review": "",
                "Structured Analysis": "",
                "AI Customer Reply": "",
                "Status": "Review Not Found"
            })

            continue

        # ---------------------------------------------------------------------
        # Retrieve Task 5 records for this review
        # ---------------------------------------------------------------------

        review_task5 = task5_df[
            task5_df["Review No"].astype(int) == review_no
        ].copy()

        if review_task5.empty:

            print(
                f"No Task 5 analysis found for Review {review_no}."
            )

            responses.append({
                "Review No": review_no,
                "Customer Review": review,
                "Structured Analysis": "",
                "AI Customer Reply": "",
                "Status": "Task 5 Output Missing"
            })

            continue

        # ---------------------------------------------------------------------
        # Keep only successful Task 5 records
        # ---------------------------------------------------------------------

        successful_rows = review_task5[
            review_task5["Status"]
            .astype(str)
            .str.lower()
            .eq("success")
        ]

        if successful_rows.empty:

            print(
                f"Task 5 analysis failed for Review {review_no}."
            )

            responses.append({
                "Review No": review_no,
                "Customer Review": review,
                "Structured Analysis": "",
                "AI Customer Reply": "",
                "Status": "Task 5 Failed"
            })

            continue

        # ---------------------------------------------------------------------
        # Build structured analysis
        # ---------------------------------------------------------------------

        structured_output = build_structured_analysis(
            successful_rows
        )

        structured_json = json.dumps(
            structured_output,
            indent=2,
            ensure_ascii=False
        )

        print("\nTask 5 Structured Analysis:")
        print(structured_json)

        # ---------------------------------------------------------------------
        # Build Task 6 response prompt
        # ---------------------------------------------------------------------

        response_prompt = build_task6_response_prompt(
            review,
            structured_output
        )

        # ---------------------------------------------------------------------
        # Send second prompt to Gemini
        # ---------------------------------------------------------------------

        print("\nGenerating Customer Response...")

        final_response = safe_call_llm(
            prompt=response_prompt,
            temperature=0.4,
            max_tokens=300
        )

        # ---------------------------------------------------------------------
        # Handle API failure
        # ---------------------------------------------------------------------

        if final_response is None:

            print(
                f"Response generation failed for Review {review_no}."
            )

            responses.append({
                "Review No": review_no,
                "Customer Review": review,
                "Structured Analysis": structured_json,
                "AI Customer Reply": "",
                "Status": "API Failed"
            })

            continue

        # ---------------------------------------------------------------------
        # Clean generated response
        # ---------------------------------------------------------------------

        cleaned_response = clean_response(
            final_response
        )

        # ---------------------------------------------------------------------
        # Save successful response
        # ---------------------------------------------------------------------

        responses.append({

            "Review No": review_no,

            "Customer Review": review,

            "Structured Analysis": structured_json,

            "AI Customer Reply": cleaned_response,

            "Status": "Success"
        })

        # ---------------------------------------------------------------------
        # Display response
        # ---------------------------------------------------------------------

        print("\nGenerated Reply:\n")
        print(cleaned_response)

    # =========================================================================
    # SAVE RESULTS
    # =========================================================================

    response_df = pd.DataFrame(responses)

    response_df.to_csv(
        OUTPUT_FILE,
        index=False,
        encoding="utf-8"
    )

    # =========================================================================
    # FINAL SUMMARY
    # =========================================================================

    print("\n")
    print("=" * 70)
    print("TASK 6 COMPLETED")
    print("=" * 70)

    print(
        f"\nReviews selected      : {len(selected_review_numbers)}"
    )

    print(
        f"Responses generated   : {len(response_df)}"
    )

    if not response_df.empty:

        successful_count = (
            response_df["Status"] == "Success"
        ).sum()

        failed_count = (
            response_df["Status"] != "Success"
        ).sum()

    else:

        successful_count = 0
        failed_count = 0

    print(
        f"Successful responses  : {successful_count}"
    )

    print(
        f"Failed responses      : {failed_count}"
    )

    print(
        f"\nCSV Saved Successfully"
    )

    print(
        f"Location : {OUTPUT_FILE}"
    )

    # =========================================================================
    # PREVIEW
    # =========================================================================

    print("\nPreview:\n")

    if not response_df.empty:

        preview_columns = [
            "Review No",
            "Customer Review",
            "AI Customer Reply",
            "Status"
        ]

        print(
            response_df[
                preview_columns
            ].to_string(index=False)
        )

    else:

        print("No customer responses were generated.")